    [Fact]
    public void HasAtLeast100Cases()
    {
        var cases = typeof(QuickAddParserTests).GetMethod(nameof(Parse))!
            .GetCustomAttributes(typeof(InlineDataAttribute), false).Length;
        Assert.True(cases >= 100, $"테스트 문장 {cases}개");
    }

    [Fact]
    public void Tokens_MarkRecognizedParts()
    {
        var result = Parser.Parse("매주 월요일 9시 주간회의 #업무 !높음 10분전 알림");

        Assert.Equal(
            [QuickAddTokenKind.Recurrence, QuickAddTokenKind.Time, QuickAddTokenKind.List, QuickAddTokenKind.Priority, QuickAddTokenKind.Reminder],
            result.Tokens.Select(t => t.Kind));
        Assert.Equal("매주 월요일", "매주 월요일 9시 주간회의 #업무 !높음 10분전 알림".Substring(result.Tokens[0].Start, result.Tokens[0].Length).Trim());
    }

    [Fact]
    public void EmptyAfterParsing_KeepsInputAsTitle()
    {
        Assert.Equal("내일", Parser.Parse("내일").Title);
    }
